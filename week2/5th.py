## ❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️❤️expandtabs() method
text = "A\tB"

# डिफ़ॉल्ट रूप से यह 8 स्पेस के हिसाब से सेट होता है
print(text.expandtabs())  

# आप इसे मैन्युअली 4 स्पेस पर सेट कर सकते हैं
print(text.expandtabs(4)) 

